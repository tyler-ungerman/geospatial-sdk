"""Project-level SDK commands."""

from __future__ import annotations

import argparse
from pathlib import Path
import re


def _scaffold_files(project_name: str, package_name: str, plugin_id: str) -> dict[str, str]:
    return {
        "pyproject.toml": f'''[build-system]
requires = ["setuptools>=68", "wheel"]
build-backend = "setuptools.build_meta"

[project]
name = "{project_name}"
version = "0.1.0"
description = "Independent geospatial plugin"
requires-python = ">=3.10"
dependencies = ["gspace-sdk>=0.1.0,<1"]

[project.optional-dependencies]
dev = ["pytest>=8"]

[project.entry-points."geospatial.modules"]
{plugin_id} = "{package_name}.plugin:setup"

[tool.setuptools.packages.find]
where = ["src"]
''',
        f"src/{package_name}/__init__.py": '"""Generated independent geospatial plugin."""\n',
        f"src/{package_name}/plugin.py": f'''"""A small typed example plugin generated by geospatial."""

from pydantic import BaseModel, Field

from gspace.plugins import register_plugin
from gspace.schemas import BoundingBox


class ExtentSummary(BaseModel):
    width_degrees: float = Field(gt=0)
    height_degrees: float = Field(gt=0)


def summarize_extent(region: BoundingBox) -> dict:
    """Return the dimensions of a WGS84 bounding box."""
    return {{
        "width_degrees": region.max_lon - region.min_lon,
        "height_degrees": region.max_lat - region.min_lat,
    }}


def setup() -> None:
    register_plugin(
        "{plugin_id}",
        "Summarize a bounding box",
        api_version="1.0.0",
        input_type=BoundingBox,
        output_type=ExtentSummary,
        resource_needs=("region",),
    )(summarize_extent)
''',
        "tests/test_plugin.py": f'''from gspace.plugins import run_plugin
from gspace.schemas import BoundingBox
from {package_name}.plugin import ExtentSummary


def test_entry_point_runs_typed_plugin():
    result = run_plugin("{plugin_id}", BoundingBox(
        min_lat=10, min_lon=20, max_lat=13, max_lon=25,
    ))
    assert isinstance(result, ExtentSummary)
    assert result.width_degrees == 5
    assert result.height_degrees == 3
''',
        "examples/run_pipeline.py": f'''"""Run the generated plugin through SDK entry-point discovery."""

from gspace.plugins import run_plugin
from gspace.schemas import BoundingBox

result = run_plugin("{plugin_id}", BoundingBox(
    min_lat=10, min_lon=20, max_lat=13, max_lon=25,
))
print(result.model_dump())
''',
        "README.md": f'''# {project_name}

Generated independent plugin package.

From the repository root, install the SDK and plugin, then run its offline
contract test and example pipeline:

```bash
python -m pip install -e ./base -e './{package_name}[dev]'
python -m pytest ./{package_name}/tests
python ./{package_name}/examples/run_pipeline.py
```

The package exposes `{plugin_id}` through `geospatial.modules`. It accepts a
typed `BoundingBox` and returns a validated `ExtentSummary` Pydantic model.
''',
    }


def create_plugin(project_name: str, destination: Path) -> Path:
    """Write a minimal independent plugin package without overwriting files."""
    normalized = project_name.strip().lower()
    if re.fullmatch(r"[a-z0-9](?:[a-z0-9_-]*[a-z0-9])?", normalized) is None:
        raise ValueError("plugin project name must use letters, digits, hyphens, or underscores")
    package_name = re.sub(r"[-]+", "_", normalized)
    if not package_name.isidentifier():
        raise ValueError("plugin name does not produce a valid Python package name")
    plugin_id = normalized.replace("_", "-")
    # Distribution names normalize hyphens and underscores equivalently, and
    # both spellings produce the same import package and entry-point ID.
    # Canonical folder names make the collision visible before a second
    # scaffold can be created beside the first one.
    target = destination / package_name
    if target.exists():
        raise FileExistsError(f"refusing to overwrite existing path: {target}")
    files = _scaffold_files(normalized, package_name, plugin_id)
    target.mkdir(parents=True)
    try:
        for relative, content in files.items():
            path = target / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    except Exception:
        # Remove only the directory this invocation created.
        import shutil
        shutil.rmtree(target)
        raise
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="geospatial", description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    plugin = commands.add_parser("plugin", help="Create a plugin package")
    plugin_commands = plugin.add_subparsers(dest="plugin_command", required=True)
    create = plugin_commands.add_parser("create", help="Create an independent plugin package")
    create.add_argument("name", help="Package/project name, for example my-map-plugin")
    create.add_argument("--path", type=Path, default=Path.cwd(), help="Parent directory for the new package")
    args = parser.parse_args(argv)
    try:
        target = create_plugin(args.name, args.path)
    except (ValueError, FileExistsError) as exc:
        parser.error(str(exc))
    print(f"Created plugin scaffold at {target}")
    print("Install it, run its tests, and execute its example pipeline; see the generated README.md.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
